// tTab(clé, langue facultative) : traduction avec repli sur le français puis sur la clé
export const tTab = (key, currentLanguage) => {
  let lang = currentLanguage;
  if (!lang) {
    try { lang = localStorage.getItem('selectedLanguage') || 'fr'; } catch { lang = 'fr'; }
  }
  const code = getLanguageCode(lang);
  return tableauTranslations[code]?.[key] ?? tableauTranslations.fr[key] ?? key;
};
